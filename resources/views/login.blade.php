                const activeRoleClasses = [
                    "bg-primary-container",
                    "text-on-primary",
                    "shadow-sm",
                ];
                const inactiveRoleClasses = [
                    "text-text-secondary",
                    "hover:text-text-primary",
                    "hover:bg-surface-container",
                ];

                function selectRole(role) {
                    document.querySelectorAll(".role-btn").forEach((btn) => {
                        const isActive = btn.dataset.role === role;
                        btn.classList.remove(
                            ...(isActive ? inactiveRoleClasses : activeRoleClasses),
                        );
                        btn.classList.add(
                            ...(isActive ? activeRoleClasses : inactiveRoleClasses),
                        );
                        btn.setAttribute("aria-pressed", isActive);
                    });

                    document.getElementById("role-input").value = role;
                    document.getElementById("role-hint").innerText =
                        roleHints[role];
                }

                function togglePasswordVisibility() {
                    const field = document.getElementById("password-input");
                    const icon = document.getElementById("eye-icon");
                    if (!field || !icon) return;

                    if (field.type === "password") {
                        field.type = "text";
                        icon.innerText = "visibility_off";
                    } else {
                        field.type = "password";
                        icon.innerText = "visibility";
                    }
                }

                function showFeedback(message) {
                    document.getElementById("feedback-text").innerText = message;
                    document
                        .getElementById("status-feedback")
                        .classList.remove("hidden");
                }

                function handleLoginSubmit(event) {
                    event.preventDefault();

                    // Interactive Feedback Simulation
                    const btn = document.querySelector(
                        '#login-form button[type="submit"]',
                    );
                    const originalText = btn.innerHTML;
                    btn.disabled = true;
                    btn.innerHTML = `<span class="material-symbols-outlined animate-spin text-[20px]">sync</span><span>Memverifikasi...</span>`;
                    showFeedback("Memproses verifikasi kredensial...");

                    setTimeout(() => {
                        btn.innerHTML = originalText;
                        btn.disabled = false;
                        showFeedback(
                            "Login berhasil (simulasi). Hubungkan form ini ke backend untuk autentikasi sebenarnya.",
                        );
                    }, 1200);
                }

                function requestOtpWhatsApp() {
                    const identifier = document.getElementById("identifier-input");

                    if (!identifier.value.trim()) {
                        showFeedback(
                            "Isi Nomor WhatsApp terlebih dahulu untuk menerima kode OTP.",
                        );
                        identifier.focus();
                        return;
                    }

                    showFeedback(
                        "Kode OTP dikirim ke WhatsApp " +
                            identifier.value.trim() +
                            " (simulasi).",
                    );
                }
